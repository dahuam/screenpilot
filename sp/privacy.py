# -*- coding: utf-8 -*-
"""隐私红线：敏感窗口标题名单 —— 智能默认下扫描不入库（2026-11-04 实操体感刀2）。

背景（P0② 红线，74 条事故的教训）：扫记事本把窗口里的账号密码明文 OCR
读出并默认写入元素书库。书库是持久化检索库（裁片+文本落磁盘），敏感窗口
内容一旦入库就长期躺在盘上。本名单挂在 pipeline.scan 的「智能默认」层：
窗口标题命中名单 → 默认按不入库处理，meta.privacy_skip=true 如实告知
agent（该窗口默认未入库、需显式 book=true 才入库）。

边界（刻意的）：
- 只拦智能默认，不拦显式意志：调用方显式传 book=true 仍可强制入库——
  名单是护栏不是牢门，agent 扫敏感面前先看 privacy_skip 自己决策；
- 只看窗口标题（子串、大小写不敏感），不做内容审查——标题是低成本高
  信号的分类器，全屏模式维持原「不入库」默认不受名单影响。

名单维护：模块级常量，直接改这里；新增敏感应用加一个词即可。
"""
import re

# 敏感窗口标题名单（子串匹配，大小写不敏感）
敏感标题名单 = (
    # 文本编辑器：无格式明文，账号密码最常见落点（记事本事故即此类）
    "记事本", "notepad", "写字板", "wordpad",
    # 密码/登录/凭据类标题
    "密码", "password", "登录", "login", "sign in", "signin",
    "凭据", "credential",
    # 聊天类：聊天内容天然隐私（WeChat/Telegram/Discord/钉钉/飞书等）
    "微信", "wechat", "qq", "telegram", "discord",
    "钉钉", "dingtalk", "飞书", "feishu", "lark",
)

_归一化缓存 = [re.sub(r"\s", "", k.lower()) for k in 敏感标题名单]


def 敏感命中(窗口标题):
    """窗口标题是否命中敏感名单。

    命中返回命中的关键词（真值，可直接当布尔用，且可入 meta 留痕）；
    未命中/空标题返回 None。子串匹配、大小写不敏感；标题与关键词同规则
    归一化（剥空白与零宽字符——Edge 标题实测带 U+200B，"sign in" 之类
    带空格词在剥空白后仍可命中）。
    """
    if not 窗口标题:
        return None
    t = re.sub(r"[\u200b\u200c\u200d\ufeff\s]", "", str(窗口标题).lower())
    for k in _归一化缓存:
        if k in t:
            return k
    return None
